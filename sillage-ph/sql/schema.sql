-- Run once in the Supabase SQL editor as the project administrator.
BEGIN;
CREATE TABLE public.perfumes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(200) NOT NULL,
  brand varchar(200) NOT NULL,
  scent_family varchar(20) NOT NULL,
  key_notes text[] NOT NULL,
  dupes text[] NOT NULL,
  gender varchar(10) NOT NULL,
  year_launched integer NOT NULL,
  concentration varchar(200) NOT NULL,
  best_season varchar(200) NOT NULL,
  best_occasion varchar(200) NOT NULL,
  dupe_size varchar(200) NOT NULL,
  vibe varchar(1000) NOT NULL,
  dupe_price_php varchar(200) NOT NULL,
  price_php_min integer NOT NULL,
  where_to_buy jsonb NOT NULL,
  other_stores jsonb NOT NULL,
  UNIQUE (brand, name),
  CHECK (gender IN ('Men','Women','Unisex')),
  CHECK (scent_family IN ('Amber','Floral','Fruity','Fresh','Woody','Gourmand','Leather')),
  CHECK (year_launched BETWEEN 1900 AND extract(year FROM CURRENT_DATE)::int),
  CHECK (price_php_min BETWEEN 0 AND 1000000),
  CHECK (cardinality(key_notes) BETWEEN 1 AND 30),
  CHECK (cardinality(dupes) BETWEEN 1 AND 30),
  CHECK (jsonb_typeof(where_to_buy) = 'object' AND where_to_buy ?& ARRAY['store','url','note'] AND where_to_buy->>'url' ~ '^https://[^/ ]+'),
  CHECK (jsonb_typeof(other_stores) = 'array' AND jsonb_array_length(other_stores) <= 30),
  CHECK (length(btrim(name)) > 0),
  CHECK (length(btrim(brand)) > 0),
  CHECK (length(btrim(scent_family)) > 0),
  CHECK (length(btrim(gender)) > 0),
  CHECK (length(btrim(concentration)) > 0),
  CHECK (length(btrim(best_season)) > 0),
  CHECK (length(btrim(best_occasion)) > 0),
  CHECK (length(btrim(dupe_size)) > 0),
  CHECK (length(btrim(vibe)) > 0),
  CHECK (length(btrim(dupe_price_php)) > 0)
);
-- Maintained automatically so searches run in PostgreSQL, including nested stores.
ALTER TABLE public.perfumes ADD COLUMN search_text text NOT NULL DEFAULT '';
CREATE FUNCTION public.perfumes_search_update() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
BEGIN
  NEW.search_text := NEW.name || ' ' || NEW.brand || ' ' || NEW.scent_family || ' ' || NEW.gender || ' ' ||
    array_to_string(NEW.key_notes, ' ') || ' ' || array_to_string(NEW.dupes, ' ') || ' ' ||
    NEW.where_to_buy::text || ' ' || NEW.other_stores::text;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.perfumes_search_update() FROM PUBLIC;
CREATE TRIGGER perfumes_search_update BEFORE INSERT OR UPDATE ON public.perfumes
  FOR EACH ROW EXECUTE FUNCTION public.perfumes_search_update();
CREATE INDEX perfumes_gender_idx ON public.perfumes(gender);
CREATE INDEX perfumes_family_idx ON public.perfumes(scent_family);
CREATE INDEX perfumes_price_idx ON public.perfumes(price_php_min, id);
CREATE INDEX perfumes_name_idx ON public.perfumes(name);
ALTER TABLE public.perfumes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.perfumes FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.perfumes_id_seq FROM anon, authenticated;
-- API uses its own login, with no schema/role management privileges.
CREATE ROLE sillage_api LOGIN NOINHERIT;
GRANT USAGE ON SCHEMA public TO sillage_api;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.perfumes TO sillage_api;
GRANT USAGE, SELECT, UPDATE ON SEQUENCE public.perfumes_id_seq TO sillage_api;
CREATE POLICY backend_access ON public.perfumes FOR ALL TO sillage_api
  USING (true) WITH CHECK (true);
COMMIT;
